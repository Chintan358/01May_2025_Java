package com.example.demo.model;

public class Question {
	
		int id;
		String questionName;
		public int getId() {
			return id;
		}
		public void setId(int id) {
			this.id = id;
		}
		public String getQuestionName() {
			return questionName;
		}
		public void setQuestionName(String questionName) {
			this.questionName = questionName;
		}
		
		
}
